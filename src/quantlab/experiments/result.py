from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from quantlab.backtest.result import BacktestResult
from quantlab.experiments.config import ExperimentConfig


@dataclass(frozen=True)
class ExperimentArtifacts:
    """
    References to artifacts generated by an experiment.

    Artifacts are outputs of the experiment/reporting pipeline,
    not part of the simulation itself.
    """

    summary_path: Path | None = None
    equity_curve_path: Path | None = None
    processed_data_path: Path | None = None


@dataclass(frozen=True)
class ExperimentResult:
    """
    Canonical result contract for a completed QuantLab experiment.

    An ExperimentResult describes both the experiment configuration
    and the complete result produced by its execution.
    """

    status: str
    dataset_name: str
    strategy_name: str
    configuration: ExperimentConfig
    backtest: BacktestResult
    trade_statistics: dict[str, Any]
    artifacts: ExperimentArtifacts

    def __post_init__(self) -> None:
        if not self.status.strip():
            raise ValueError("status must be a non-empty string")

        if not self.dataset_name.strip():
            raise ValueError(
                "dataset_name must be a non-empty string"
            )

        if not self.strategy_name.strip():
            raise ValueError(
                "strategy_name must be a non-empty string"
            )

        if not isinstance(
            self.configuration,
            ExperimentConfig,
        ):
            raise TypeError(
                "configuration must be an ExperimentConfig"
            )

        if not isinstance(
            self.backtest,
            BacktestResult,
        ):
            raise TypeError(
                "backtest must be a BacktestResult"
            )

        if not isinstance(
            self.trade_statistics,
            dict,
        ):
            raise TypeError(
                "trade_statistics must be a dictionary"
            )

        if not isinstance(
            self.artifacts,
            ExperimentArtifacts,
        ):
            raise TypeError(
                "artifacts must be an ExperimentArtifacts"
            )

    @property
    def metrics(self) -> dict[str, Any]:
        """Backward-compatible access to backtest metrics."""
        return self.backtest.metrics

    @property
    def equity_curve(self):
        """Access the realized backtest equity curve."""
        return self.backtest.equity_curve

    @property
    def data_trust(self):
        """Access the backtest Data Trust assessment."""
        return self.backtest.data_trust

    @property
    def summary_path(self) -> Path | None:
        """Backward-compatible access to the experiment summary."""
        return self.artifacts.summary_path

    @property
    def equity_curve_path(self) -> Path | None:
        """Backward-compatible access to the equity-curve artifact."""
        return self.artifacts.equity_curve_path

    @property
    def processed_data_path(self) -> Path | None:
        """Backward-compatible access to processed-data artifacts."""
        return self.artifacts.processed_data_path
